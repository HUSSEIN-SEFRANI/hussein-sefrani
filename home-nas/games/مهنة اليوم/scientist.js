// مهنة اليوم — العالِم 👩‍🔬: تجارب في المختبر. قراءة المخبار، والرسم البياني، والتجربة العادلة، والطفو والغوص،
// وخلط الألوان، والمتوسط، والوحدات. كل جواب صحيح يضيف اكتشافاً إلى دفتر المختبر.
(() => {
  "use strict";
  const r = (a, b) => Jobs.rnd(a, b);
  const num = (ans, unit, html, why, spread = [1, 2, 5, 10]) => ({ html, ans, unit, why, opts: Jobs.numOptions(ans, 3, spread) });
  const txt = (html, ans, bad, why) => ({ html, ans, why, opts: K.shuffle([ans, ...bad]) });
  const STEPS = [
    (L) => { const v = r(2, 9) * (L >= 2 ? 5 : 10); return num(v, "مل", `<h3>🧪 المخبار</h3>${cyl(v)}<p>كم مليلتراً من الماء في المخبار؟</p>`, `نقرأ عند سطح الماء: ${v} مل`, [5, 10]); },
    () => { const h = [r(8, 14), r(3, 7), r(1, 2)];
      return txt(`<h3>🌱 تجربة الضوء</h3>${bars([["☀️ ضوء", h[0]], ["⛅ ظل", h[1]], ["🌑 ظلام", h[2]]], "سم")}<p>زرعنا 3 نبتات متشابهة. ماذا نستنتج؟</p>`,
        "النبتة تحتاج الضوء لتنمو", ["النبتة تنمو أكثر في الظلام", "الضوء لا يؤثر"], "النبتة في الضوء نمت أكثر: الضوء ضروري لصنع غذائها."); },
    () => { const h = [r(5, 15), r(5, 15), r(5, 15)], m = Math.max(...h) - Math.min(...h);
      return num(m, "سم", `<h3>📊 الرسم البياني</h3>${bars([["🅰️", h[0]], ["🅱️", h[1]], ["🅲", h[2]]], "سم")}<p>كم الفرق بين الأطول والأقصر؟</p>`, `${Math.max(...h)} − ${Math.min(...h)} = ${m}`); },
    () => { const o = K.pick([["🪵 قطعة خشب", "🔩 مسمار حديد", "🪨 حجر"], ["🍎 تفاحة", "🪙 قطعة نقود", "🔑 مفتاح"], ["🧊 مكعب ثلج", "⚓ مرساة", "🧲 مغناطيس"]]);
      return txt(`<h3>💧 يطفو أم يغوص؟</h3><p>وضعنا ثلاثة أشياء في حوض ماء. أيها <b>يطفو</b>؟</p>`, o[0], o.slice(1), "الأشياء الأخف من الماء بالنسبة لحجمها تطفو."); },
    () => { const m = K.pick([["🔴 أحمر + 🟡 أصفر", "🟠 برتقالي", ["🟢 أخضر", "🟣 بنفسجي"]], ["🔵 أزرق + 🟡 أصفر", "🟢 أخضر", ["🟠 برتقالي", "🟤 بني"]], ["🔴 أحمر + 🔵 أزرق", "🟣 بنفسجي", ["🟢 أخضر", "🟡 أصفر"]]]);
      return txt(`<h3>🎨 خلط الألوان</h3><p>${m[0]} = ؟</p>`, m[1], m[2], `${m[0]} = ${m[1]}`); },
    () => txt(`<h3>⚖️ التجربة العادلة</h3><p>نريد أن نعرف: هل <b>كمية الماء</b> تؤثر على نمو النبتة؟ ماذا نفعل؟</p>`,
      "نغيّر الماء فقط، ونبقي الضوء والتربة كما هي", ["نغيّر الماء والضوء والتربة معاً", "نسقي نبتة واحدة فقط"], "في التجربة العادلة نغيّر شيئاً واحداً فقط."),
    (L) => { const a = [r(18, 26), r(18, 26), r(18, 26)]; const s = a[0] + a[1] + a[2], k = s % 3; a[2] -= k; const avg = (s - k) / 3;
      return num(avg, "°", `<h3>🌡️ المتوسط</h3><p>قسنا حرارة الغرفة 3 مرات: <b>${a.join("، ")}</b>. ما المتوسط؟</p>`, `(${a.join(" + ")}) ÷ 3 = ${avg}`); },
    () => { const u = K.pick([["1 لتر", 1000, "مل"], ["1 كيلوغرام", 1000, "غرام"], ["1 متر", 100, "سم"], ["1 كيلومتر", 1000, "متر"]]);
      return num(u[1], u[2], `<h3>📏 الوحدات</h3><p>${u[0]} = كم ${u[2]}؟</p>`, `${u[0]} = ${u[1]} ${u[2]}`, [10, 100, 900]); },
    () => { const q = K.pick([
        ["ماذا يحدث لمكعب ثلج تحت الشمس؟", "يذوب ويصير ماء", ["يصير أكبر", "يصير حجراً"]],
        ["الماء عندما يغلي يصير…", "بخاراً (غاز)", ["ثلجاً", "رملاً"]],
        ["المغناطيس يجذب…", "المسمار الحديد", ["الورقة", "قطعة الخشب"]],
        ["لماذا نرى البرق قبل أن نسمع الرعد؟", "الضوء أسرع من الصوت", ["الصوت أسرع من الضوء", "الرعد يأتي من مكان آخر"]],
        ["أين يذوب السكر أسرع؟", "في الماء الساخن", ["في الماء البارد جداً", "في الزيت"]],
      ]); return txt(`<h3>🔬 سؤال المختبر</h3><p>${q[0]}</p>`, q[1], q[2], ""); },
    (L) => { const start = r(10, 20) * 10, after = start - r(2, 6) * 10; return num(start - after, "مل", `<h3>🔥 التبخر</h3>${cyl(after)}<p>وضعنا <b>${start} مل</b> ماء في الشمس يومين، فصار كما في المخبار. كم مل تبخّر؟</p>`, `${start} − ${after} = ${start - after}`, [10, 20]); },
  ];
  function cyl(v) {
    const top = 200 - v * 1.6; let marks = "";
    for (let m = 0; m <= 100; m += 10) marks += `<line x1="60" x2="${m % 50 ? 72 : 80}" y1="${200 - m * 1.6}" y2="${200 - m * 1.6}" stroke="#1e3a8a" stroke-width="${m % 50 ? 1.5 : 3}"/>${m % 20 ? "" : `<text x="86" y="${206 - m * 1.6}" font-size="13" font-weight="800" fill="#1e3a8a">${m}</text>`}`;
    return `<svg class="cyl" viewBox="0 0 130 215"><rect x="20" y="25" width="60" height="178" rx="6" fill="#f8fafc" stroke="#64748b" stroke-width="3"/><rect x="23" y="${top}" width="54" height="${200 - top}" fill="#7dd3fc"/>${marks}</svg>`;
  }
  function bars(rows, unit) {
    const mx = Math.max(...rows.map((x) => x[1]));
    return `<div class="chart">${rows.map(([n, h]) => `<div><b>${h}</b><i style="height:${(h / mx) * 20}vh"></i><small>${n}</small></div>`).join("")}<span class="unit">${unit}</span></div>`;
  }

  function how() {
    return `<p>أنت عالمة في المختبر 👩‍🔬. العلماء يكتشفون الأشياء بالتجربة والقياس.</p>
      <ul><li>اقرأ <b>المخبار</b> و<b>الرسم البياني</b> بدقة.</li><li>صمّم <b>تجربة عادلة</b>: نغيّر شيئاً واحداً فقط.</li><li>استنتج النتيجة واكتبها في دفتر المختبر 📒.</li></ul>
      <p class="goal">مهمة اليوم: <b>20 اكتشافاً</b> تقريباً.</p>`;
  }
  function start(api) {
    Jobs.stages(api, {
      icon: "🧪", label: "اكتشافات", confetti: "🧪✨🔬",
      total: (L) => 18 + 2 * L,
      make: (L, i) => STEPS[i % STEPS.length](L),
      art: (R, total) => `<div class="lab"><span class="emo">👩‍🔬</span><div class="shelfx">${K.range(0, total).map((k) => `<span class="emo ${k < R.done ? "" : "off"}">${["🧪", "⚗️", "🧫", "🔭", "🧲"][k % 5]}</span>`).join("")}</div><small>📒 ${R.done} اكتشافاً</small></div>`,
      msg: ["عالمة مبدعة! 🔬🏆", "تجارب ناجحة! 👏", "انتهت التجارب! 💪"],
    });
  }
  Jobs.register("scientist", { how, start });
})();
